def _rr(x, y, w, h, r=0.0) -> str:
    return rect_path(x, y, w, h, r)


def _bar(x1, y1, x2, y2, t=2.0) -> str:
    """Полоса толщиной t от точки к точке."""
    dx, dy = x2 - x1, y2 - y1
    ln = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / ln * t / 2, dx / ln * t / 2
    return _poly([(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)])


def _ring_sector(cx, cy, ro, ri, a0, sweep) -> str:
    """Кольцевой сектор: углы в градусах, 0° — вправо, по часовой стрелке."""
    a1 = a0 + sweep
    large = 1 if sweep > 180 else 0

    def p(r, a):
        return f"{cx + r * math.cos(math.radians(a)):.3f} {cy + r * math.sin(math.radians(a)):.3f}"
    return (f"M{p(ro, a0)} A{ro} {ro} 0 {large} 1 {p(ro, a1)} L{p(ri, a1)} "
            f"A{ri} {ri} 0 {large} 0 {p(ri, a0)} Z")


def _scaled(d: str, k: float, cx: float = 12, cy: float = 12) -> str:
    """Тот же контур, уменьшенный к центру (для значков-«контуров»)."""
    return to_string(transform(parse(d), (k, 0, 0, k, cx * (1 - k), cy * (1 - k))))


